export const p1617 = (lang: Lang, key: string): string =>
  PUBLIER1617[lang]?.[key] ?? PUBLIER1617.en[key] ?? key;

/** Phrase « N prévenus » / « aucun », N et rayon réels de la réponse serveur. */
export function notifiedSentence(lang: Lang, n: number, km: number, walk: boolean): string {
  const role = walk ? "walker" : "sitter";
  if (n <= 0) return p1617(lang, `none_${role}`);
  const key = n === 1 ? `notified_${role}_one` : `notified_${role}_many`;
  return p1617(lang, key).replace("{n}", String(n)).replace("{km}", String(km));
}

/** « N propriétaires cherchent un gardien à {city} cette semaine » ; "" si 0. */
export function statsSentence(lang: Lang, n: number, city: string): string {
  if (n <= 0) return "";
  return p1617(lang, n === 1 ? "stats_one" : "stats_many").replace("{n}", String(n)).replace("{city}", city);
}
