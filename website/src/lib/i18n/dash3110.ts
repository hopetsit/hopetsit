export const DASH3110: Partial<Record<Lang, D>> = { fr: FR, en: EN };

export function dz(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const d = DASH3110[lang] || EN;
  let s = d[key] ?? EN[key] ?? FR[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
