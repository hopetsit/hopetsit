export function d620(lang: Lang, key: string): string {
  return DATES620[lang]?.[key] ?? DATES620.fr[key] ?? DATES620.en[key] ?? key;
}

/** « 5 visites », « 1 jour », « 3 nuits », « 1 balade ». */
export function qtyLabel620(lang: Lang, quantity: number, unit: string): string {
  const u = unit === "night" ? "night" : unit === "visit" ? "visit" : unit === "walk" ? "walk" : "day";
  const key = quantity === 1 ? `qty_${u}_1` : `qty_${u}_n`;
  return d620(lang, key).replace("{n}", String(quantity));
}

/** Libellé court d'unité pour « 12 €/visite » : visite, jour, nuit, balade, h, sem, mois. */
export function unitShort620(lang: Lang, unit: string): string {
  const u = ["day", "night", "visit", "walk", "hour", "week", "month"].includes(unit) ? unit : "day";
  return d620(lang, `unit_${u}`);
}

/** « par visite », « par jour »… */
export function unitLong620(lang: Lang, unit: string): string {
  const u = ["day", "night", "visit", "walk", "hour"].includes(unit) ? unit : "day";
  return d620(lang, `unit_long_${u}`);
}

/** Libellé d'un service du catalogue (texte du serveur si fourni dans cette langue, sinon le nôtre). */
export function serviceLabel620(lang: Lang, key: string, labels?: Record<string, string>): string {
  const srv = labels && (labels[lang] || labels[`${lang}-${lang.toUpperCase()}`]);
  if (srv && srv.trim()) return srv.trim();
  return d620(lang, `svc_${key}`);
}
