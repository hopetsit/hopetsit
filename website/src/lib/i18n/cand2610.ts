export function c2610(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = CAND2610[lang]?.[key] ?? CAND2610.fr[key] ?? CAND2610.en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), raw);
}
