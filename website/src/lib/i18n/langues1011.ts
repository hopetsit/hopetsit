/** Texte `key` dans la langue `lang` (repli : français, puis la clé). `{nom}` remplacé par vars.nom. */
export function g1011(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const d = G1011[lang] || G1011.fr;
  let s = d[key] ?? G1011.fr[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
