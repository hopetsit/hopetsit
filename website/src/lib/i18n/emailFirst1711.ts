export function ef(lang: Lang | string, key: string, vars: Record<string, string | number> = {}): string {
  const l = (lang in EMAIL_FIRST_1711 ? lang : "fr") as Lang;
  let s = EMAIL_FIRST_1711[l][key] ?? EMAIL_FIRST_1711.fr[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
